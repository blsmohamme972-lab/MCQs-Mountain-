#!/usr/bin/env python3
"""
validate.py v2 — MCQ book package validator (package schema 1)

The ONE gate for every book. The AI runs it before delivering a ZIP,
and the server runs the exact same file before publishing.
Do not edit this file to make a package pass.

Usage:
    python validate.py BOOK_ID_v1.zip [more.zip ...]
    python validate.py --require-audit BOOK_ID_v1.zip      (server mode)

Exit code 0 = PASS, 1 = FAIL. Warnings never fail a package.
No third-party libraries needed.

v2 changes: ZIP safety checks (path traversal, absolute paths, symlinks,
encryption, decompression bombs, too many files), report.md required,
unexpected files are errors (system junk is ignored), images wider than
1600 px are errors, audit.json support (--require-audit).
"""

import hashlib
import json
import os
import re
import sys
import zipfile
import unicodedata

# ---------------------------------------------------------------- settings
# Edit this list to match your app's specialties (single source of truth).
ALLOWED_SPECIALTIES = [
    "Anesthesiology", "Cardiology", "Cardiothoracic & Vascular Surgery",
    "Clinical Neurophysiology", "Dermatology", "ENT", "Emergency Medicine",
    "Family Medicine", "General Surgery", "Histopathology",
    "Internal Medicine", "Neurosurgery", "Obstetrics & Gynecology",
    "Oncology", "Ophthalmology", "Orthopedics", "Pediatrics",
    "Plastic & Reconstructive Surgery", "Psychiatry", "Radiology",
    "Urology", "Basic Sciences", "Pharmacology", "Dentistry", "Other",
]
ALLOWED_FIELDS = ["medicine", "pharmacy", "dentistry"]
ALLOWED_COLLECTIONS = ["textbook", "past_exam"]
ALLOWED_TYPES = ["sba", "mtf", "multi", "emq"]
ALLOWED_ANSWER_SOURCES = ["book_key", "inline_marked"]

MAX_ZIP_BYTES = 19 * 1024 * 1024          # Telegram bot download limit is 20 MB
MAX_UNCOMPRESSED_BYTES = 200 * 1024 * 1024
MAX_ZIP_ENTRIES = 5000
MAX_COMPRESSION_RATIO = 100               # higher = likely decompression bomb
MAX_IMAGE_BYTES = 1_500_000
MAX_COVER_BYTES = 400_000
TARGET_IMAGE_WIDTH = 1200                 # above this = warning
MAX_IMAGE_WIDTH = 1600                    # above this = error
TOP_LEVEL_FILES = {"book.json", "questions.jsonl", "report.md", "cover.webp", "audit.json"}
IGNORED_JUNK = ("__MACOSX/", ".DS_Store", "Thumbs.db")
AUDIT_LEVELS = ["match", "warning", "mismatch", "unverifiable"]
OPTION_COUNT = {"sba": (3, 8), "mtf": (2, 10), "multi": (3, 12), "emq": (5, 26)}
LETTERS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ"

BOOK_ID_RE = re.compile(r"^[A-Z0-9][A-Z0-9-]{2,40}$")
IMAGE_NAME_RE = re.compile(r"^images/L(\d{4,6})_(e?\d{1,2})\.webp$")
LABEL_PREFIX_RE = re.compile(r"^\s*\(?[A-Za-z]\s*[\).:]\s+")
EMBEDDED_OPTIONS_RE = re.compile(r"(^|\n)\s*\(?A[\).]\s.+\n\s*\(?B[\).]\s", re.S)
ORDER_SENSITIVE_RE = re.compile(
    r"\b(all|none|both|neither) of the (above|following)\b|\b(a|b|c|d) (and|&) (b|c|d|e)\b"
    r"|\bonly [a-e]\b", re.I)
JUNK_RE = re.compile(r"copyright|all rights reserved|\bisbn\b|www\.|\.com\b", re.I)
BROKEN_HYPHEN_RE = re.compile(r"[a-z]- [a-z]")


# ---------------------------------------------------------------- helpers
class Report:
    def __init__(self, name):
        self.name = name
        self.errors = []
        self.warnings = []

    def err(self, where, msg):
        self.errors.append(f"{where}: {msg}")

    def warn(self, where, msg):
        self.warnings.append(f"{where}: {msg}")


def bad_chars(text):
    """Return a description of forbidden characters, or ''."""
    for ch in text:
        cp = ord(ch)
        if ch == "\ufffd":
            return "replacement character (broken encoding)"
        if 0xFB00 <= cp <= 0xFB06:
            return f"ligature '{ch}' (split it into normal letters)"
        if 0xE000 <= cp <= 0xF8FF:
            return "private-use symbol (PDF font junk)"
        if unicodedata.category(ch) == "Cc" and ch not in "\n\t":
            return "control character"
    return ""


def check_text(rep, where, text, kind):
    if not isinstance(text, str):
        rep.err(where, f"{kind} must be text")
        return
    problem = bad_chars(text)
    if problem:
        rep.err(where, f"{kind} contains {problem}")
    if kind in ("stem", "option"):
        if text.rstrip().endswith("-") and not text.rstrip().endswith("--"):
            rep.err(where, f"{kind} ends with '-' (truncated?)")
        if JUNK_RE.search(text):
            rep.warn(where, f"{kind} contains page header/footer-like text")
    if kind == "stem":
        if re.search(r"\banswer\s*[:=]", text, re.I):
            rep.err(where, "stem contains 'Answer:' (answer leaked into the question)")
        if EMBEDDED_OPTIONS_RE.search(text):
            rep.err(where, "stem still contains the A./B. options block")
        if len(text) > 4000:
            rep.warn(where, "stem is very long (two questions merged?)")
    if BROKEN_HYPHEN_RE.search(text):
        rep.warn(where, f"{kind} has a line-break hyphen like 'hypo- thermia'")
    if text.count("(") != text.count(")"):
        rep.warn(where, f"{kind} has unbalanced parentheses")


def norm(text):
    return re.sub(r"\W+", " ", str(text).lower()).strip()


def webp_width(data):
    """Read width from a WebP header; None if unknown."""
    if len(data) < 30 or data[:4] != b"RIFF" or data[8:12] != b"WEBP":
        return None
    chunk = data[12:16]
    try:
        if chunk == b"VP8X":
            return 1 + int.from_bytes(data[24:27], "little")
        if chunk == b"VP8 ":
            return int.from_bytes(data[26:28], "little") & 0x3FFF
        if chunk == b"VP8L":
            b = data[21:25]
            return 1 + (((b[1] & 0x3F) << 8) | b[0])
    except Exception:
        return None
    return None


def is_webp(data):
    return len(data) >= 12 and data[:4] == b"RIFF" and data[8:12] == b"WEBP"


# ---------------------------------------------------------------- book.json
def check_book(rep, book):
    w = "book.json"
    required = ["schema", "book_id", "title", "authors", "edition", "field",
                "specialty", "collection_type", "language", "version",
                "part", "id_range", "chapters", "skipped"]
    for key in required:
        if key not in book:
            rep.err(w, f"missing '{key}'")
    if rep.errors:
        return None

    if book["schema"] != 1:
        rep.err(w, "schema must be 1")
    if not isinstance(book["book_id"], str) or not BOOK_ID_RE.match(book["book_id"]):
        rep.err(w, "book_id must be UPPERCASE letters/digits/hyphens, 3–41 chars")
    if not str(book["title"]).strip():
        rep.err(w, "title is empty")
    if not isinstance(book["authors"], list):
        rep.err(w, "authors must be a list")
    if book["field"] not in ALLOWED_FIELDS:
        rep.err(w, f"field must be one of {ALLOWED_FIELDS}")
    if book["specialty"] not in ALLOWED_SPECIALTIES:
        rep.err(w, f"specialty '{book['specialty']}' is not in ALLOWED_SPECIALTIES")
    if book["collection_type"] not in ALLOWED_COLLECTIONS:
        rep.err(w, f"collection_type must be one of {ALLOWED_COLLECTIONS}")
    if not isinstance(book["version"], int) or book["version"] < 1:
        rep.err(w, "version must be an integer >= 1")

    part = book["part"]
    if not (isinstance(part, dict) and isinstance(part.get("index"), int)
            and isinstance(part.get("total"), int) and 1 <= part["index"] <= part["total"]):
        rep.err(w, "part must be {\"index\": n, \"total\": m} with 1 <= n <= m")
        part = {"index": 1, "total": 1}

    rng = book["id_range"]
    if not (isinstance(rng, list) and len(rng) == 2 and all(isinstance(x, int) for x in rng)
            and 1 <= rng[0] <= rng[1]):
        rep.err(w, "id_range must be [first_local_id, last_local_id]")
        rng = None

    if part["total"] == 1 and rng:
        exp = book.get("expected_count")
        if isinstance(exp, int) and rng[1] - rng[0] + 1 != exp:
            rep.err(w, f"id_range covers {rng[1] - rng[0] + 1} questions but expected_count is {exp}")

    chapters = {}
    if not isinstance(book["chapters"], list) or not book["chapters"]:
        rep.err(w, "chapters must be a non-empty list")
    else:
        for c in book["chapters"]:
            if not (isinstance(c, dict) and isinstance(c.get("id"), int) and str(c.get("title", "")).strip()):
                rep.err(w, f"bad chapter entry {c!r}")
                continue
            if c["id"] in chapters:
                rep.err(w, f"duplicate chapter id {c['id']}")
            chapters[c["id"]] = c["title"]

    skipped = {}
    if not isinstance(book["skipped"], list):
        rep.err(w, "skipped must be a list")
    else:
        for s in book["skipped"]:
            if not (isinstance(s, dict) and isinstance(s.get("local_id"), int) and str(s.get("reason", "")).strip()):
                rep.err(w, f"bad skipped entry {s!r} (needs local_id + reason)")
                continue
            skipped[s["local_id"]] = s["reason"]

    return {"part": part, "range": rng, "chapters": chapters, "skipped": skipped}


# ---------------------------------------------------------------- questions
def check_answer(rep, where, q, n_opts):
    t, a = q["type"], q["answer"]
    valid = LETTERS[:n_opts]
    if t in ("sba", "emq"):
        if not (isinstance(a, str) and len(a) == 1 and a in valid):
            rep.err(where, f"answer must be one letter from {valid[0]}–{valid[-1]}, got {a!r}")
    elif t == "multi":
        if not (isinstance(a, list) and len(a) >= 2 and all(isinstance(x, str) and x in valid for x in a)
                and len(set(a)) == len(a)):
            rep.err(where, f"multi answer must be a list of 2+ distinct letters from {valid}, got {a!r}")
    elif t == "mtf":
        if not (isinstance(a, list) and len(a) == n_opts and all(x in ("T", "F") for x in a)):
            rep.err(where, f"mtf answer must be a list of {n_opts} 'T'/'F' values, got {a!r}")


def check_question(rep, q, ctx, image_files, used_images):
    lid = q.get("local_id")
    where = f"Q{lid}" if isinstance(lid, int) else "question ?"
    required = ["local_id", "chapter_id", "type", "source_number", "stem", "options",
                "answer", "answer_source", "explanation", "images",
                "explanation_images", "no_shuffle", "source_page", "flag"]
    missing = [k for k in required if k not in q]
    if missing:
        rep.err(where, f"missing fields {missing}")
        return
    if not isinstance(lid, int):
        rep.err(where, "local_id must be an integer")
        return

    if q["chapter_id"] not in ctx["chapters"]:
        rep.err(where, f"chapter_id {q['chapter_id']} not in book.json chapters")
    if q["type"] not in ALLOWED_TYPES:
        rep.err(where, f"type must be one of {ALLOWED_TYPES}")
        return
    if not str(q["source_number"]).strip():
        rep.err(where, "source_number is empty")
    if q["answer_source"] not in ALLOWED_ANSWER_SOURCES:
        rep.err(where, f"answer_source must be one of {ALLOWED_ANSWER_SOURCES} (answers are never guessed)")
    if not isinstance(q["source_page"], int) or q["source_page"] < 1:
        rep.err(where, "source_page must be a page number >= 1")
    if not isinstance(q["no_shuffle"], bool):
        rep.err(where, "no_shuffle must be true/false")
    if q["type"] == "emq" and not str(q.get("group_id", "")).strip():
        rep.err(where, "emq questions need a group_id shared by the theme")

    stem = q["stem"]
    check_text(rep, where, stem, "stem")
    if isinstance(stem, str) and len(stem.strip()) < 10:
        rep.err(where, "stem is too short (under 10 characters)")
    if str(q.get("lead_in", "")):
        check_text(rep, where, q["lead_in"], "lead_in")

    opts = q["options"]
    if not isinstance(opts, list):
        rep.err(where, "options must be a list")
        return
    lo, hi = OPTION_COUNT[q["type"]]
    if not lo <= len(opts) <= hi:
        rep.err(where, f"{q['type']} needs {lo}–{hi} options, has {len(opts)}")
    seen = set()
    for i, o in enumerate(opts):
        ow = f"{where} option {LETTERS[i] if i < 26 else i}"
        if not isinstance(o, str) or not o.strip():
            rep.err(ow, "empty option")
            continue
        check_text(rep, ow, o, "option")
        if LABEL_PREFIX_RE.match(o):
            rep.err(ow, "option still starts with its label like 'A.' or '(b)'")
        key = norm(o)
        if key in seen:
            rep.warn(ow, "duplicate option text")
        seen.add(key)
        if ORDER_SENSITIVE_RE.search(o) and not q["no_shuffle"]:
            rep.err(ow, "option depends on order ('all of the above' etc.) — set no_shuffle: true")

    check_answer(rep, where, q, len(opts))

    if not isinstance(q["explanation"], str):
        rep.err(where, "explanation must be text ('' if the book has none)")
    elif q["explanation"]:
        check_text(rep, where, q["explanation"], "explanation")

    if not isinstance(q["flag"], str):
        rep.err(where, "flag must be text ('' if none)")
    elif q["flag"].strip():
        rep.warn(where, f"AI flag: {q['flag'].strip()[:120]}")

    for field, explan in (("images", False), ("explanation_images", True)):
        imgs = q[field]
        if not isinstance(imgs, list):
            rep.err(where, f"{field} must be a list")
            continue
        if len(imgs) > 6:
            rep.err(where, f"too many {field} (max 6)")
        for name in imgs:
            path = f"images/{name}"
            m = IMAGE_NAME_RE.match(path)
            if not m:
                rep.err(where, f"image name '{name}' must look like L0041_1.webp (or L0041_e1.webp for explanations)")
                continue
            if int(m.group(1)) != lid:
                rep.err(where, f"image '{name}' belongs to another question number")
            if m.group(2).startswith("e") != explan:
                rep.err(where, f"image '{name}' is in the wrong list ({field})")
            if path not in image_files:
                rep.err(where, f"image '{name}' is missing from images/")
            used_images.add(path)


# ---------------------------------------------------------------- zip safety
def is_junk(name):
    return name.startswith("__MACOSX/") or any(name.endswith(j) for j in IGNORED_JUNK[1:])


def check_zip_safety(rep, zf):
    """Return the list of safe, non-junk file names. Unsafe members are errors."""
    infos = zf.infolist()
    if len(infos) > MAX_ZIP_ENTRIES:
        rep.err("zip", f"{len(infos)} entries — more than {MAX_ZIP_ENTRIES}")
        return []
    total = 0
    seen = set()
    safe = []
    junk = 0
    for info in infos:
        name = info.filename
        if name.endswith("/"):
            continue
        if is_junk(name):
            junk += 1
            continue
        if "\\" in name or name.startswith("/") or re.match(r"^[A-Za-z]:", name):
            rep.err("zip", f"'{name}' has an absolute or Windows-style path")
            continue
        if ".." in name.split("/"):
            rep.err("zip", f"'{name}' tries to escape the folder (path traversal)")
            continue
        if (info.external_attr >> 16) & 0o170000 == 0o120000:
            rep.err("zip", f"'{name}' is a symlink")
            continue
        if info.flag_bits & 0x1:
            rep.err("zip", f"'{name}' is encrypted")
            continue
        if name in seen:
            rep.err("zip", f"'{name}' appears twice")
            continue
        seen.add(name)
        total += info.file_size
        if info.compress_size > 0 and info.file_size / info.compress_size > MAX_COMPRESSION_RATIO:
            rep.err("zip", f"'{name}' expands {info.file_size // max(info.compress_size, 1)}x (decompression bomb?)")
            continue
        safe.append(name)
    if total > MAX_UNCOMPRESSED_BYTES:
        rep.err("zip", f"unpacks to {total / 1048576:.0f} MB — over {MAX_UNCOMPRESSED_BYTES // 1048576} MB")
    if junk:
        rep.warn("zip", f"{junk} system junk files ignored (__MACOSX, .DS_Store)")
    return safe


# ---------------------------------------------------------------- audit.json
def check_audit(rep, zf, names, question_ids, require):
    """audit.json is written by audit.py in the AI chat, where the PDF is."""
    if "audit.json" not in names:
        if require:
            rep.err("audit", "audit.json is required (run audit.py next to the PDF)")
        return {}
    try:
        audit = json.loads(zf.read("audit.json").decode("utf-8"))
    except Exception as e:
        rep.err("audit", f"audit.json is not valid JSON ({e})")
        return {}
    if not isinstance(audit, dict):
        rep.err("audit", "audit.json must be a JSON object")
        return {}
    missing_keys = [k for k in ("schema", "questions_sha256", "pdf_sha256", "scanned", "results")
                    if k not in audit]
    if missing_keys:
        rep.err("audit", f"audit.json missing {missing_keys}")
        return {}
    real_hash = hashlib.sha256(zf.read("questions.jsonl")).hexdigest()
    if audit["questions_sha256"] != real_hash:
        rep.err("audit", "audit.json was made for a different questions.jsonl — re-run audit.py")
    counts = {lvl: 0 for lvl in AUDIT_LEVELS}
    covered = set()
    for r in audit["results"] if isinstance(audit["results"], list) else []:
        if not (isinstance(r, dict) and isinstance(r.get("local_id"), int) and r.get("level") in AUDIT_LEVELS):
            rep.err("audit", f"bad audit result {str(r)[:80]}")
            continue
        covered.add(r["local_id"])
        counts[r["level"]] += 1
        if r["level"] == "mismatch":
            rep.err(f"Q{r['local_id']}", f"audit mismatch with the PDF: {str(r.get('detail', ''))[:120]}")
    missing = sorted(set(question_ids) - covered)
    if missing:
        rep.err("audit", f"{len(missing)} questions not audited, e.g. {missing[:10]}")
    if counts["warning"] or counts["unverifiable"]:
        rep.warn("audit", f"{counts['warning']} audit warnings + {counts['unverifiable']} unverifiable "
                          f"→ these questions will be HELD for review")
    return counts


# ---------------------------------------------------------------- package
def validate_zip(path, require_audit=False):
    rep = Report(path)
    try:
        zf = zipfile.ZipFile(path)
    except Exception as e:
        rep.err("zip", f"cannot open ({e})")
        return rep, {}

    size = os.path.getsize(path)
    if size > MAX_ZIP_BYTES:
        rep.err("zip", f"{size / 1048576:.1f} MB — over 19 MB, split into parts")

    names = check_zip_safety(rep, zf)
    if rep.errors:
        return rep, {}

    for req in ("book.json", "questions.jsonl", "report.md"):
        if req not in names:
            rep.err("zip", f"missing {req} at the top level of the ZIP")
    if rep.errors:
        return rep, {}

    try:
        book = json.loads(zf.read("book.json").decode("utf-8"))
    except Exception as e:
        rep.err("book.json", f"invalid JSON ({e})")
        return rep, {}
    ctx = check_book(rep, book)
    if ctx is None:
        return rep, {}

    image_files = {n for n in names if n.startswith("images/")}
    for n in names:
        if n in TOP_LEVEL_FILES or n in image_files:
            continue
        rep.err("zip", f"unexpected file '{n}' (only book.json, questions.jsonl, report.md, "
                       f"cover.webp, audit.json and images/ are allowed)")

    # cover
    if ctx["part"]["index"] == 1:
        if "cover.webp" not in names:
            rep.err("cover", "cover.webp is required in part 1")
        else:
            data = zf.read("cover.webp")
            if not is_webp(data):
                rep.err("cover", "cover.webp is not a real WebP file")
            elif len(data) > MAX_COVER_BYTES:
                rep.err("cover", f"cover.webp is {len(data) // 1000} KB (max 400 KB)")
            else:
                wd = webp_width(data)
                if wd and not 300 <= wd <= 1200:
                    rep.warn("cover", f"cover width {wd}px (aim for ~600px)")

    # images
    for n in sorted(image_files):
        if not IMAGE_NAME_RE.match(n):
            rep.err("images", f"bad image file name '{n}'")
            continue
        data = zf.read(n)
        if not is_webp(data):
            rep.err("images", f"'{n}' is not a real WebP file")
        elif len(data) > MAX_IMAGE_BYTES:
            rep.err("images", f"'{n}' is {len(data) // 1000} KB (max 1500 KB)")
        else:
            wd = webp_width(data)
            if wd and wd > MAX_IMAGE_WIDTH:
                rep.err("images", f"'{n}' is {wd}px wide (hard max {MAX_IMAGE_WIDTH})")
            elif wd and wd > TARGET_IMAGE_WIDTH:
                rep.warn("images", f"'{n}' is {wd}px wide (target {TARGET_IMAGE_WIDTH})")

    # questions
    used_images = set()
    ids, stems, full = [], {}, {}
    no_expl = 0
    types = {}
    raw = zf.read("questions.jsonl").decode("utf-8", errors="replace")
    for ln, line in enumerate(raw.splitlines(), 1):
        if not line.strip():
            continue
        try:
            q = json.loads(line)
        except Exception as e:
            rep.err(f"questions.jsonl line {ln}", f"invalid JSON ({e})")
            continue
        if not isinstance(q, dict):
            rep.err(f"questions.jsonl line {ln}", "each line must be a JSON object")
            continue
        n_err = len(rep.errors)
        check_question(rep, q, ctx, image_files, used_images)
        lid = q.get("local_id")
        if not isinstance(lid, int):
            continue
        ids.append(lid)
        if len(rep.errors) == n_err:
            types[q["type"]] = types.get(q["type"], 0) + 1
            if not q["explanation"].strip():
                no_expl += 1
            s = norm(q["stem"])
            f = s + "|" + "|".join(norm(o) for o in q["options"])
            if f in full:
                rep.err(f"Q{lid}", f"exact duplicate of Q{full[f]}")
            elif s in stems and q["type"] != "emq" and len(s) > 40:
                rep.warn(f"Q{lid}", f"same stem as Q{stems[s]} (different options)")
            full.setdefault(f, lid)
            stems.setdefault(s, lid)

    # numbering: every id in range present or declared skipped
    dup_ids = sorted({i for i in ids if ids.count(i) > 1})
    for i in dup_ids:
        rep.err(f"Q{i}", "local_id used more than once")
    if ids != sorted(ids):
        rep.warn("questions.jsonl", "questions are not in book order")
    rng = ctx["range"]
    if rng:
        present = set(ids)
        for i in range(rng[0], rng[1] + 1):
            if i not in present and i not in ctx["skipped"]:
                rep.err(f"Q{i}", "missing (not in questions.jsonl and not listed in skipped)")
            if i in present and i in ctx["skipped"]:
                rep.err(f"Q{i}", "listed in skipped but also present")
        outside = sorted(i for i in present if not rng[0] <= i <= rng[1])
        if outside:
            rep.err("questions.jsonl", f"local_ids outside id_range: {outside[:10]}")

    for n in sorted(image_files - used_images):
        rep.warn("images", f"'{n}' is not used by any question")

    audit_counts = check_audit(rep, zf, names, set(ids), require_audit)

    stats = {
        "audit": audit_counts,
        "book_id": book.get("book_id"),
        "title": book.get("title"),
        "part": f"{ctx['part']['index']}/{ctx['part']['total']}",
        "questions": len(set(ids)),
        "types": types,
        "skipped": len(ctx["skipped"]),
        "images": len(image_files),
        "no_explanation": no_expl,
    }
    return rep, stats


def print_report(rep, stats, limit=60):
    print("=" * 64)
    print(f"Package : {rep.name}")
    if stats:
        print(f"Book    : {stats['book_id']} — {stats['title']} (part {stats['part']})")
        print(f"Counts  : {stats['questions']} questions {stats['types']}, "
              f"{stats['skipped']} skipped, {stats['images']} images, "
              f"{stats['no_explanation']} without explanation")
        if stats.get("audit"):
            print(f"Audit   : {stats['audit']}")
    for label, items in (("ERRORS", rep.errors), ("WARNINGS", rep.warnings)):
        if items:
            print(f"\n{label} ({len(items)}):")
            for line in items[:limit]:
                print(f"  - {line}")
            if len(items) > limit:
                print(f"  ... and {len(items) - limit} more")
    print()
    if rep.errors:
        print(f"RESULT: FAIL ({len(rep.errors)} errors)")
    else:
        print(f"RESULT: PASS ({len(rep.warnings)} warnings)")


def main():
    args = sys.argv[1:]
    require_audit = "--require-audit" in args
    paths = [a for a in args if a != "--require-audit"]
    if not paths:
        print(__doc__)
        sys.exit(2)
    failed = False
    for path in paths:
        rep, stats = validate_zip(path, require_audit)
        print_report(rep, stats)
        failed = failed or bool(rep.errors)
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()